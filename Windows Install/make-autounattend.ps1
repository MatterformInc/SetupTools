#Requires -Version 5.1
<#
.SYNOPSIS
  Writes an autounattend.xml that makes Windows 11 setup create a local account and skip the
  "Let's add your Microsoft account" screens (and the network requirement).

.DESCRIPTION
  Copy the generated file to the root of a Windows install USB. Setup picks it up automatically.
  It only automates the account and privacy screens: language, region, keyboard and disk selection
  stay manual, so it can never wipe a drive by itself.

  The username and password you type are written only into the generated file, never into this repo.
  The password is stored the standard unattend way (Base64, not encrypted), so treat the USB as sensitive.
#>
param(
    [string]$OutputPath,
    [string]$UserName,          # skip the prompts by passing these
    [SecureString]$Password,
    [string]$ComputerName
)

function ConvertTo-XmlText([string]$s) { [System.Security.SecurityElement]::Escape($s) }

# Unattend "obfuscated" password format: Base64 of UTF-16LE (password + "Password").
function ConvertTo-UnattendPassword([string]$plain) {
    [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($plain + 'Password'))
}

Write-Host ''
Write-Host 'Create autounattend.xml (local account, no Microsoft account prompt)' -ForegroundColor White
Write-Host ''

$user = $UserName
do {
    if (-not $user) { $user = (Read-Host 'Local account name (e.g. Install)').Trim() }
    $valid = $user -and $user.Length -le 20 -and $user -notmatch '[\\/"\[\]:|<>+=;,?*@]'
    if (-not $valid) { Write-Host '  Use up to 20 characters, no \ / " [ ] : | < > + = ; , ? * @' -ForegroundColor Yellow; $user = $null }
} until ($valid)

$secure = if ($Password) { $Password } elseif ($PSBoundParameters.ContainsKey('UserName')) { New-Object SecureString } else { Read-Host 'Password (leave blank for none)' -AsSecureString }
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
try { $plainPassword = [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }

$computerName = if ($PSBoundParameters.ContainsKey('UserName')) { "$ComputerName".Trim() } else { (Read-Host 'Computer name (leave blank to let Windows pick)').Trim() }
if ($computerName -and ($computerName.Length -gt 15 -or $computerName -notmatch '^[A-Za-z0-9-]+$')) {
    Write-Host '  Computer name must be up to 15 letters, digits or hyphens. Letting Windows pick.' -ForegroundColor Yellow
    $computerName = ''
}

$computerNameXml = if ($computerName) { "`n            <ComputerName>$(ConvertTo-XmlText $computerName)</ComputerName>" } else { '' }
$passwordXml = ConvertTo-UnattendPassword $plainPassword
$userXml = ConvertTo-XmlText $user

$xml = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by SetupTools\Windows Install\make-autounattend.ps1
     Local account + no Microsoft account screens. Language, region, keyboard and disk stay manual. -->
<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">
    <settings pass="specialize">
        <component name="Microsoft-Windows-Shell-Setup" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">$computerNameXml
        </component>
        <component name="Microsoft-Windows-Deployment" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
            <RunSynchronous>
                <RunSynchronousCommand wcm:action="add">
                    <Order>1</Order>
                    <Description>Allow setup without an internet connection</Description>
                    <Path>reg.exe add "HKLM\SOFTWARE\Microsoft\Windows\CurrentVersion\OOBE" /v BypassNRO /t REG_DWORD /d 1 /f</Path>
                </RunSynchronousCommand>
            </RunSynchronous>
        </component>
    </settings>
    <settings pass="oobeSystem">
        <component name="Microsoft-Windows-Shell-Setup" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
            <OOBE>
                <HideEULAPage>true</HideEULAPage>
                <HideOnlineAccountScreens>true</HideOnlineAccountScreens>
                <HideLocalAccountScreen>true</HideLocalAccountScreen>
                <HideOEMRegistrationScreen>true</HideOEMRegistrationScreen>
                <ProtectYourPC>3</ProtectYourPC>
            </OOBE>
            <UserAccounts>
                <LocalAccounts>
                    <LocalAccount wcm:action="add">
                        <Name>$userXml</Name>
                        <DisplayName>$userXml</DisplayName>
                        <Group>Administrators</Group>
                        <Password>
                            <Value>$passwordXml</Value>
                            <PlainText>false</PlainText>
                        </Password>
                    </LocalAccount>
                </LocalAccounts>
            </UserAccounts>
        </component>
    </settings>
</unattend>
"@

# Where to write: a Windows install USB if one is plugged in, otherwise next to this script.
if (-not $OutputPath) {
    $usb = Get-CimInstance Win32_LogicalDisk -Filter 'DriveType=2' -ErrorAction SilentlyContinue |
        Where-Object { (Test-Path "$($_.DeviceID)\sources\install.wim") -or (Test-Path "$($_.DeviceID)\sources\install.esd") -or (Test-Path "$($_.DeviceID)\sources\install.swm") } |
        Select-Object -First 1
    if ($usb) {
        $answer = Read-Host "Windows install USB found at $($usb.DeviceID) ($($usb.VolumeName)). Write autounattend.xml there? [Y/n]"
        if ($answer -notmatch '^[nN]') { $OutputPath = "$($usb.DeviceID)\autounattend.xml" }
    }
    if (-not $OutputPath) { $OutputPath = Join-Path $PSScriptRoot 'autounattend.xml' }
}

[IO.File]::WriteAllText($OutputPath, $xml, (New-Object Text.UTF8Encoding($false)))
$plainPassword = $null

Write-Host ''
Write-Host "Written: $OutputPath" -ForegroundColor Green
if ($OutputPath -notmatch '^[A-Za-z]:\\autounattend\.xml$') {
    Write-Host 'Copy it to the ROOT of your Windows install USB (next to setup.exe).' -ForegroundColor Yellow
    Write-Host 'Do not commit it: it contains the account password (only Base64-encoded).' -ForegroundColor Yellow
}
Write-Host 'Boot the PC from the USB; setup will create the local account and skip the Microsoft account screens.'
